ALL_TRANSLATIONS = {"en": EN, "ru": RU}


class I18n:
    def __init__(self, language="en"):
        self.language = language
        self.translations = dict(ALL_TRANSLATIONS)
        self._load_custom_translations()

    def _load_custom_translations(self):
        custom_dir = os.path.join(TRANSLATIONS_DIR)
        if os.path.exists(custom_dir):
            for fname in os.listdir(custom_dir):
                if fname.endswith(".json"):
                    lang = os.path.splitext(fname)[0]
                    try:
                        with open(os.path.join(custom_dir, fname), "r", encoding="utf-8") as f:
                            data = json.load(f)
                            if lang in self.translations:
                                self.translations[lang].update(data)
                            else:
                                self.translations[lang] = data
                    except Exception:
                        pass

    def set_language(self, lang):
        if lang in self.translations:
            self.language = lang

    def t(self, key, *args):
        d = self.translations.get(self.language, self.translations.get("en", {}))
        text = d.get(key, EN.get(key, key))
        if args:
            try:
                text = text.format(*args)
            except (IndexError, KeyError):
                pass
        return text

    def get_language_name(self, lang=None):
        return LANGUAGES.get(lang or self.language, lang)

    def get_available_languages(self):
        langs = dict(LANGUAGES)
        for code in self.translations:
            if code not in langs:
                langs[code] = code
        return langs
